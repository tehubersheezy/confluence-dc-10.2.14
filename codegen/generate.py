from __future__ import annotations

import json
import keyword
import re
import shutil
import subprocess
import sys
import textwrap
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from names import API, EXPERIMENTAL, NOTES  # noqa: E402

OUT = ROOT / "src" / "confluence_dc" / "_api"
HEADER = "# Generated by codegen/generate.py from api-inventory/inventory.json. Do not edit.\n"
RESERVED = {"self", "body", "files", "data"}
GENERIC = {
    "get",
    "index",
    "list",
    "create",
    "update",
    "delete",
    "post",
    "put",
    "find",
    "search",
    "add",
    "remove",
    "save",
    "set",
    "handle",
    "execute",
    "query",
    "fetch",
    "store",
    "do_get",
    "do_post",
    "get_all",
    "find_all",
    "get_content",
    "get_data",
    "get_entity",
}
CLASS_SUFFIXES = ("RestResource", "Resource", "Rest", "Controller", "Endpoint", "Service", "Api")


def snake(name: str) -> str:
    name = re.sub(r"[^0-9A-Za-z]+", "_", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"_+", "_", name).strip("_").lower()
    if not name or name[0].isdigit():
        name = "p_" + name
    return name


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def safe(name: str) -> str:
    return name + "_" if keyword.iskeyword(name) or name in RESERVED else name


def class_noun(cls: str) -> str:
    stem = cls.split(".")[-1]
    for suffix in CLASS_SUFFIXES:
        if stem.endswith(suffix) and stem != suffix:
            stem = stem[: -len(suffix)]
            break
    return snake(stem)


def py_type(java: str, path: bool = False) -> str:
    if path:
        return "str | int"
    base = java.split("<")[0]
    if base in ("int", "long", "short", "Integer", "Long", "Short"):
        return "int"
    if base in ("boolean", "Boolean"):
        return "bool"
    if base in ("double", "float", "Double", "Float"):
        return "float"
    if base in ("List", "Set", "Collection", "Iterable", "SortedSet") or java.endswith("[]"):
        return "Sequence[Any] | str"
    return "str"


# ----------------------------------------------------------------- naming


def internal_namespace(base: str, bases: set[str]) -> str:
    segs = [s for s in base.split("/")[2:] if s]
    version = segs[-1] if segs and re.fullmatch(r"\d+(\.\d+)*|latest", segs[-1]) else None
    if version:
        segs = segs[:-1]
    name = "_".join(snake(s.split(".")[-1] if "." in s else s) for s in segs)
    siblings = {b for b in bases if b != base and b.rsplit("/", 1)[0] == base.rsplit("/", 1)[0]}
    if version and siblings:
        name += "_v" + version.split(".")[0]
    return name


def name_internal(endpoints: list[dict]) -> None:
    """Assign e['py_name'] within one internal namespace, resolving collisions."""

    def first_choice(e: dict) -> str:
        java = snake(e["java"])
        noun = class_noun(e["class"])
        if java in GENERIC:
            verb = "get" if java == "index" else java
            return f"{verb}_{noun}" if noun and noun not in verb else verb
        return java

    names = {id(e): first_choice(e) for e in endpoints}
    for _ in range(4):
        counts = defaultdict(list)
        for e in endpoints:
            counts[names[id(e)]].append(e)
        clashes = [group for group in counts.values() if len(group) > 1]
        if not clashes:
            return_names(endpoints, names)
            return
        for group in clashes:
            nouns = {class_noun(e["class"]) for e in group}
            for e in group:
                cur = names[id(e)]
                noun = class_noun(e["class"])
                if len(nouns) > 1 and not cur.startswith(noun):
                    names[id(e)] = f"{noun}_{cur}"
                else:
                    literal = [s for s in e["path"].split("/") if s and "{" not in s][-1:]
                    params = re.findall(r"\{(\w+)\}", e["path"])
                    suffix = (
                        "_by_" + "_".join(snake(p) for p in params)
                        if params
                        else "_" + snake(literal[0] if literal else e["method"])
                    )
                    if not cur.endswith(suffix):
                        names[id(e)] = cur + suffix
                    else:
                        names[id(e)] = f"{cur}_{e['method'].lower()}"
    # last resort: numeric suffixes
    seen: dict[str, int] = {}
    for e in endpoints:
        n = names[id(e)]
        seen[n] = seen.get(n, 0) + 1
        if seen[n] > 1:
            names[id(e)] = f"{n}_{seen[n]}"
    return_names(endpoints, names)


def return_names(endpoints: list[dict], names: dict[int, str]) -> None:
    for e in endpoints:
        e["py_name"] = safe(names[id(e)])


# ----------------------------------------------------------------- rendering


def humanize(java: str) -> str:
    words = snake(java).replace("_", " ")
    return words[:1].upper() + words[1:] + "."


def model_summary(java_type: str | None, models: dict[str, dict]) -> str | None:
    if not java_type:
        return None
    inner = java_type
    m = re.fullmatch(r"(?:List|Set|Collection)<(.+)>", java_type)
    if m:
        inner = m.group(1)
    simple = inner.split("<")[0]
    hits = [v for k, v in models.items() if k.split(".")[-1] == simple]
    if not hits:
        return None
    fields = list(hits[0]["fields"])
    return ", ".join(fields[:24]) + (", ..." if len(fields) > 24 else "")


def media(value) -> tuple[str, ...]:
    return tuple(v for v in value if isinstance(v, str)) if isinstance(value, list) else ()


def render_method(e: dict, models: dict[str, dict]) -> str:
    path_wires = re.findall(r"\{(\w+)\}", e["path"])
    used: set[str] = set()

    def pyname(wire: str) -> str:
        n = safe(snake(wire))
        while n in used:
            n += "_"
        used.add(n)
        return n

    sig: list[str] = ["self"]
    spec_path, spec_query, spec_form, spec_headers = [], [], [], []
    docs: list[str] = []
    for wire in path_wires:
        n = pyname(wire)
        sig.append(f"{n}: str | int")
        spec_path.append((n, wire))

    multipart = any("multipart" in c for c in media(e["consumes"])) or any(
        p["in"] == "multipart" for p in e["params"]
    )
    has_body = e["body"] is not None and not multipart
    if multipart:
        sig.append("files: Any")
        used.add("files")
    elif has_body:
        required = e["method"] in ("POST", "PUT", "PATCH")
        sig.append("body: Any" if required else "body: Any = None")
        used.add("body")

    keyword_params = []
    for p in e["params"]:
        if p["in"] == "path":
            continue
        n = pyname(p["name"])
        t = py_type(p["type"])
        keyword_params.append(f"{n}: {t} | None = None")
        if p["in"] == "query":
            spec_query.append((n, p["name"]))
        elif p["in"] in ("form", "multipart"):
            spec_form.append((n, p["name"]))
        elif p["in"] == "header":
            spec_headers.append((n, p["name"]))
        else:
            spec_query.append((n, p["name"]))  # bean/matrix/cookie: best effort as query
        note = f"{p['in']} ``{p['name']}``, {p['type']}"
        if p.get("default") not in (None, ""):
            note += f", server default ``{p['default']}``"
        docs.append(f"{n}: {note}.")
    if multipart:
        keyword_params.append("data: Mapping[str, Any] | None = None")
        used.add("data")
    if keyword_params:
        sig.append("*")
        sig += keyword_params

    def tup(pairs):
        return "(" + "".join(f"({a!r}, {b!r}), " for a, b in pairs) + ")" if pairs else "()"

    consumes = media(e["consumes"])
    produces = media(e["produces"])
    spec_args = [f"{e['method']!r}", f"{e['path']!r}"]
    if spec_path:
        spec_args.append(f"path_params={tup(spec_path)}")
    if spec_query:
        spec_args.append(f"query={tup(spec_query)}")
    if spec_form:
        spec_args.append(f"form={tup(spec_form)}")
    if spec_headers:
        spec_args.append(f"headers={tup(spec_headers)}")
    if has_body:
        spec_args.append("body='body'")
    if multipart:
        spec_args.append("multipart=True")
    if consumes:
        spec_args.append(f"consumes={consumes!r}")
    if produces and produces != ("application/json",):
        spec_args.append(f"produces={produces!r}")

    doc = e.get("doc") or {}
    summary = e.get("py_summary") or doc.get("summary") or humanize(e["java"])
    summary = summary.strip().rstrip(".") + "."
    lines = [summary, "", f"``{e['method']} {e['path']}``"]
    if e.get("deprecated"):
        lines += ["", "Deprecated by Atlassian."]
    desc = re.sub(r"<[^>]+>", "", doc.get("description") or "").strip()
    if desc:
        desc = re.sub(r"\s+", " ", desc)
        lines += [""] + textwrap.wrap(desc[:700] + ("..." if len(desc) > 700 else ""), 88)
    if docs:
        lines += ["", "Args:"] + [f"    {d}" for d in docs]
    if multipart:
        lines += [
            "",
            "``files`` is passed to httpx as multipart files, e.g.",
            '``{"file": ("name.png", fh, "image/png")}``; ``data`` adds form fields',
            "such as ``comment`` or ``minorEdit``.",
        ]
    if has_body:
        fields = model_summary(e["body"], models)
        text = f"Body: ``{e['body']}``" + (f" with fields {fields}." if fields else ".")
        lines += [""] + textwrap.wrap(text, 88)
    note = NOTES.get((e["method"], e["path"]))
    if note:
        lines += [""] + note.splitlines()
    if e["returns"] not in ("void", "Response", "Object", None):
        lines += ["", f"Returns ``{e['returns']}``."]
    body = textwrap.indent(
        '"""' + "\n".join(lines).replace("\\", "\\\\").replace('"""', "'''") + '\n"""', " " * 8
    )
    body = "\n".join(line.rstrip() for line in body.splitlines())
    signature = ", ".join(sig)
    return (
        f"    @endpoint(Spec({', '.join(spec_args)}))\n"
        f"    def {e['py_name']}({signature}) -> Any:\n{body}\n"
    )


def render_module(cls_name: str, doc: str, endpoints: list[dict], models: dict) -> str:
    methods = "\n".join(
        render_method(e, models) for e in sorted(endpoints, key=lambda e: e["py_name"])
    )
    needs_seq = "Sequence[" in methods
    needs_map = "Mapping[" in methods
    imports = ["from __future__ import annotations", ""]
    abc = [n for n, used in (("Mapping", needs_map), ("Sequence", needs_seq)) if used]
    if abc:
        imports.append(f"from collections.abc import {', '.join(abc)}")
    imports += [
        "from typing import Any",
        "",
        "from ..._endpoint import Namespace, Spec, endpoint",
        "",
    ]
    return (
        HEADER
        + "\n".join(imports)
        + f"\n\nclass {cls_name}(Namespace):\n"
        + textwrap.indent(f'"""{doc}"""', "    ")
        + "\n\n"
        + methods
    )


def main() -> None:
    inv = json.loads((ROOT / "api-inventory" / "inventory.json").read_text())
    models = inv["models"]
    endpoints = [e for e in inv["endpoints"] if e["audience"] == "user"]

    groups: dict[tuple[str, str], list[dict]] = defaultdict(list)
    missing = []
    for e in endpoints:
        key = (e["method"], e["path"])
        if e["tier"] in ("api", "experimental"):
            table = API if e["tier"] == "api" else EXPERIMENTAL
            if key not in table:
                missing.append(key)
                continue
            ns, name, *summary = table[key]
            e["py_name"] = name
            if summary:
                e["py_summary"] = summary[0]
            groups[(e["tier"], ns)].append(e)
    if missing:
        sys.exit("No curated name for:\n  " + "\n  ".join(f"{m} {p}" for m, p in missing))
    stale = (set(API) | set(EXPERIMENTAL)) - {(e["method"], e["path"]) for e in endpoints}
    if stale:
        print(
            "warning: curated names with no user-facing endpoint:", sorted(stale), file=sys.stderr
        )

    internal = [e for e in endpoints if e["tier"] == "internal"]
    bases = {e["module_base"] for e in internal}
    plugin_of: dict[str, str] = {}
    for e in internal:
        ns = internal_namespace(e["module_base"], bases)
        groups[("internal", ns)].append(e)
        plugin_of[ns] = f"{e['plugin_name']} ({e['module_base']})"
    for (tier, _ns), es in groups.items():
        if tier == "internal":
            name_internal(es)

    if OUT.exists():
        shutil.rmtree(OUT)
    wiring: dict[str, list[tuple[str, str, str]]] = defaultdict(list)
    for (tier, ns), es in sorted(groups.items()):
        prefix = {"api": "", "experimental": "Experimental", "internal": "Internal"}[tier]
        cls_name = prefix + camel(ns) + "Api"
        if tier == "api":
            doc = f"``/rest/api``: {ns.replace('_', ' ')}."
        elif tier == "experimental":
            doc = (
                f"``/rest/experimental``: {ns.replace('_', ' ')}. Marked experimental by Atlassian."
            )
        else:
            doc = (
                f"{plugin_of[ns]}.\n\n    Undocumented API used by the Confluence UI. It works "
                "for regular users but can\n    change between Confluence releases without "
                "notice.\n    "
            )
        target = OUT / tier / f"{ns}.py"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render_module(cls_name, doc, es, models))
        wiring[tier].append((ns, cls_name, f".{tier}.{ns}"))

    for tier in ("api", "experimental", "internal"):
        (OUT / tier / "__init__.py").write_text(HEADER)

    lines = [HEADER, "from __future__ import annotations", "", "from typing import Any", ""]
    for tier in ("api", "experimental", "internal"):
        for _ns, cls_name, mod in wiring[tier]:
            lines.append(f"from {mod} import {cls_name}")
    lines += [
        "",
        "",
        "class ExperimentalNamespaces:",
        '    """``/rest/experimental``: real features Atlassian still marks experimental."""',
        "",
        "    def __init__(self, client: Any) -> None:",
    ]
    lines += [f"        self.{ns} = {cls}(client)" for ns, cls, _ in wiring["experimental"]]
    lines += [
        "",
        "",
        "class InternalNamespaces:",
        '    """Undocumented APIs the Confluence UI uses. They can change between releases."""',
        "",
        "    def __init__(self, client: Any) -> None:",
    ]
    lines += [f"        self.{ns} = {cls}(client)" for ns, cls, _ in wiring["internal"]]
    lines += [
        "",
        "",
        "class ApiNamespaces:",
        '    """Attributes shared by Confluence and AsyncConfluence."""',
        "",
    ]
    lines += [f"    {ns}: {cls}" for ns, cls, _ in wiring["api"]]
    lines += [
        "    experimental: ExperimentalNamespaces",
        "    internal: InternalNamespaces",
        "",
        "    def __init__(self) -> None:",
    ]
    lines += [f"        self.{ns} = {cls}(self)" for ns, cls, _ in wiring["api"]]
    lines += [
        "        self.experimental = ExperimentalNamespaces(self)",
        "        self.internal = InternalNamespaces(self)",
        "",
    ]
    (OUT / "__init__.py").write_text("\n".join(lines))

    subprocess.run(["ruff", "format", "--quiet", str(OUT)], check=False)
    total = sum(len(es) for es in groups.values())
    tiers = {t: sum(1 for k in groups if k[0] == t) for t in ("api", "experimental", "internal")}
    print(f"{total} endpoints in {len(groups)} namespaces {tiers}")


if __name__ == "__main__":
    main()
